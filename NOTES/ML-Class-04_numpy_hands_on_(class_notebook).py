import numpy as np
import time

print(np.__version__)

"""## 2. Why NumPy? List vs NumPy speed
Adding a million numbers. First with a plain Python loop, then the same job with a list and with a NumPy array.
"""

nums = list(range(1_000_000))

total = 0
for n in nums:
    total = total + n
print(total)

nums = list(range(1_000_000))
arr  = np.arange(1_000_000)

# Run each 10 times so one slow run doesn't mislead us
t0 = time.perf_counter()
for _ in range(10):
    sum(nums)
list_time = (time.perf_counter() - t0) / 10

t0 = time.perf_counter()
for _ in range(10):
    arr.sum()
numpy_time = (time.perf_counter() - t0) / 10

print(f"list : {list_time:.5f} seconds")
print(f"numpy: {numpy_time:.5f} seconds")
print(f"NumPy is about {list_time / numpy_time:.0f}x faster")

"""NumPy works on the whole array at once in fast C code, so it is many times quicker than looping in Python. This is why every ML library is built on it.

## 3. Creating arrays

**From a list:** a 1D array
"""

arr = np.array([10, 20, 30, 40])
print(arr)

"""**A 2D array** (rows and columns). One value is a decimal, so NumPy stores every value as a float."""

arr1 = np.array([
    [10.2, 20, 30, 40],
    [2, 4, 8, 9]
])
print(arr1)

"""**Ready-made arrays**"""

arr1 = np.ones((2, 3))      # 2 rows, 3 columns, all 1.0
print(arr1)

e = np.linspace(0, 1, 5)     # 5 evenly spaced values from 0 to 1
print(e)

a = np.arange(5, 55, 5)      # start 5, stop before 55, step 5
print(a)

"""## 4. Array attributes: shape, type, dtype"""

arr1 = np.array([
    [10.2, 20, 30, 40],
    [2, 4, 8, 9]
])

print(arr1.shape)    # (rows, columns)
print(type(arr1))    # it is a NumPy array
print(arr1.dtype)    # float64, because of 10.2

"""Compare with a normal Python list:"""

l1 = [2, 3, 4, 5]
print(type(l1))

"""## 5. Reshaping
`reshape` changes rows × columns without changing the values. The new shape must hold exactly the same number of elements.
"""

a = np.arange(5, 55, 5)
print(a)

m = a.reshape(2, 5)    # 10 elements → 2 rows × 5 columns
print(m)

"""10 elements cannot fit into 2 × 4 = 8 places, so NumPy raises a `ValueError`:"""

try:
    a.reshape(2, 4)
except ValueError as err:
    print("ValueError:", err)

"""## 6. Indexing
Positions start at 0. Negative indexes count from the end: `-1` is the last element.
"""

arr = np.array([10, 20, 30, 40])
print(arr[0])     # first
print(arr[-1])    # last

"""In a 2D array, use `[row, column]`. `:` means *all*."""

m = np.array([[1, 2, 3],
              [4, 5, 6]])

print(m[1, :])    # row 1 (the second row), all columns

"""## 7. Slicing
`array[start:stop:step]`. Leave any part empty to use its default: start = 0, stop = end, step = 1.
"""

arr2 = np.array([10, 20, 30, 40, 50, 60])
print(arr2[::])    # everything

"""## 8. Boolean masks
A comparison on an array gives one True/False per element. Put that mask inside `[ ]` to keep only the True values.
"""

scores = np.array([45, 82, 67, 91, 38, 74])

mask = scores >= 60
print(mask)            # True where the score is 60 or more
print(scores[mask])    # keep only those scores

"""To combine two conditions use `&` (and) or `|` (or), with brackets around each condition. Writing `60 <= scores < 80` raises *"The truth value of an array with more than one element is ambiguous"*."""

scores = np.array([45, 82, 67, 91, 38, 74])

print(scores[(scores >= 60) & (scores < 80)])

